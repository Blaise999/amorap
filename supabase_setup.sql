  key text PRIMARY KEY, value text NOT NULL
);
CREATE TABLE IF NOT EXISTS amorap_booking.reservations (
  id text PRIMARY KEY, token text NOT NULL,
  status text NOT NULL CHECK (status IN ('awaiting_payment','payment_review','confirmed','cancelled','expired')),
  created bigint NOT NULL, expires bigint NOT NULL,
  payload text NOT NULL, reference text NOT NULL DEFAULT ''
);
CREATE INDEX IF NOT EXISTS amorap_reservations_status_idx ON amorap_booking.reservations (status, expires);
CREATE TABLE IF NOT EXISTS amorap_booking.messages (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created bigint NOT NULL, payload text NOT NULL
);
CREATE TABLE IF NOT EXISTS amorap_booking.photos (
  name text PRIMARY KEY, mime text NOT NULL CHECK (mime IN ('image/jpeg','image/png','image/webp')),
  content bytea NOT NULL CHECK (octet_length(content) <= 6000000)
);
CREATE TABLE IF NOT EXISTS amorap_booking.admin_sessions (
  token text PRIMARY KEY, csrf text NOT NULL, expiry bigint NOT NULL
);
